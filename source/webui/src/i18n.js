function browserLanguageToLocale(browserLanguage) {
  const b = (browserLanguage || 'en').toLowerCase()
  if (b.startsWith('zh-hant') || b.startsWith('zh-tw') ||
      b.startsWith('zh-hk') || b.startsWith('zh-mo')) return 'zh-Hant'
  if (b.startsWith('zh')) return 'zh-Hans'
  if (b.startsWith('ar')) return 'ar'
  if (b.startsWith('ja')) return 'ja'
  if (b.startsWith('ko')) return 'ko'
  if (b.startsWith('fr')) return 'fr'
  if (b.startsWith('de')) return 'de'
  if (b.startsWith('it')) return 'it'
  if (b.startsWith('es')) return 'es'
  if (b.startsWith('pt')) return 'pt-BR'
  if (b.startsWith('ru')) return 'ru'
  if (b.startsWith('pl')) return 'pl'
  if (b.startsWith('th')) return 'th'
  return 'en'
}

export function resolveLanguage(serverLanguage) {
  if (serverLanguage && dictionaries[serverLanguage]) return serverLanguage
  return browserLanguageToLocale(navigator.language)
}

export function translate(language, key) {
  return (dictionaries[language] || english)[key] || english[key] || key
}
